// What leaves Preflight: the System Security Plan (Markdown to read and edit, OSCAL JSON for tools such as eMASS
// importers and FedRAMP's automation), the POA&M (OSCAL JSON and a spreadsheet-ready CSV), and a full backup.
import type { Catalog, Control, PoamItem, State } from './model.js';
import { assessmentOf, evidenceFor, fmtDate, inScope, isOverdue, poamsFor, readiness, sha256, today } from './logic.js';

export const OSCAL_VERSION = '1.2.1';
const NS = 'https://github.com/jasonzawacki-arch/preflight/ns';
const PROFILE = (b: string) =>
  `https://raw.githubusercontent.com/usnistgov/oscal-content/main/nist.gov/SP800-53/rev5/json/NIST_SP-800-53_rev5_${b.toUpperCase()}-baseline_profile.json`;

const STATUS_LABEL: Record<string, string> = { satisfied: 'Satisfied', partial: 'Partially satisfied', 'not-satisfied': 'Not satisfied', 'not-applicable': 'Not applicable' };
const OSCAL_STATE: Record<string, string> = { satisfied: 'implemented', partial: 'partial', 'not-satisfied': 'planned', 'not-applicable': 'not-applicable' };
const RISK_STATE: Record<string, string> = { open: 'open', 'in-progress': 'remediating', 'risk-accepted': 'deviation-approved', closed: 'closed' };

/** Stable UUIDs: the same system and control always get the same id, so re-exports diff cleanly. */
export function uuidFor(...parts: string[]): string {
  let h1 = 0x811c9dc5, h2 = 0x01000193, h3 = 0x9e3779b9, h4 = 0x85ebca6b;
  for (const ch of parts.join('|')) {
    const c = ch.charCodeAt(0);
    h1 = Math.imul(h1 ^ c, 0x01000193) >>> 0;
    h2 = Math.imul(h2 ^ c, 0x5bd1e995) >>> 0;
    h3 = Math.imul(h3 ^ c, 0x27d4eb2d) >>> 0;
    h4 = Math.imul(h4 ^ c, 0x165667b1) >>> 0;
  }
  const hex = [h1, h2, h3, h4].map((x) => x.toString(16).padStart(8, '0')).join('');
  return `${hex.slice(0, 8)}-${hex.slice(8, 12)}-4${hex.slice(13, 16)}-${'89ab'[parseInt(hex[16], 16) & 3]}${hex.slice(17, 20)}-${hex.slice(20, 32)}`;
}

const slug = (s: string) => s.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '') || 'role';
const sysKey = (s: State) => s.system.name || 'system';
const nowStamp = () => new Date().toISOString().replace(/\.\d+Z$/, 'Z');

function statementText(c: Control): string {
  return c.s.map(([d, l, t]) => `${'  '.repeat(d)}${l ? l + ' ' : ''}${t}`).join('\n');
}

// ---------- SSP, Markdown ----------
export function sspMarkdown(cat: Catalog, s: State): string {
  const sys = s.system,
    r = readiness(cat, s),
    out: string[] = [];
  const line = (x = '') => out.push(x);
  line(`# System Security Plan: ${sys.name || 'Untitled system'}`);
  line();
  line(`Draft generated by Preflight on ${fmtDate(today())}. Controls from ${cat.source}, published ${fmtDate(cat.published)}.`);
  if (s.demo) line(`\n> Sample data for a fictional system.`);
  line();
  line('## 1. System information');
  line();
  line('| | |');
  line('|---|---|');
  const row = (k: string, v: string) => line(`| ${k} | ${(v || '_Not set_').replace(/\|/g, '\\|').replace(/\n/g, ' ')} |`);
  row('System name', sys.name + (sys.short ? ` (${sys.short})` : ''));
  row('Security categorization', `${sys.baseline[0].toUpperCase()}${sys.baseline.slice(1)} (FIPS 199)`);
  row('Control baseline', `NIST SP 800-53 Rev. 5 ${sys.baseline} baseline${sys.privacy ? ' plus the privacy baseline' : ''}`);
  row('Operational status', sys.status.replace(/-/g, ' '));
  row('System owner', sys.owner);
  row('Information system security officer', sys.isso);
  line();
  line('### System description');
  line();
  line(sys.description || '_Describe the system, its purpose and its users._');
  line();
  line('### Authorization boundary');
  line();
  line(sys.boundary || '_Describe what is inside the boundary: components, networks, data stores and interconnections._');
  line();
  line('## 2. Readiness at a glance');
  line();
  line(`${r.total} controls in scope. ${r.satisfied} satisfied, ${r.partial} partially satisfied, ${r.notSatisfied} not satisfied, ${r.na} not applicable, ${r.unassessed} not assessed. Readiness score ${r.score}%.`);
  line();
  line(`Open POA&M items: ${r.openPoams.high} high, ${r.openPoams.moderate} moderate, ${r.openPoams.low} low; ${r.overdue} overdue.`);
  line();
  line('## 3. Control implementation');
  const scope = inScope(cat, s);
  for (const f of cat.families) {
    const cs = scope.filter((c) => c.f === f.id);
    if (!cs.length) continue;
    line();
    line(`### ${f.id}: ${f.name}`);
    for (const c of cs) {
      const a = assessmentOf(s, c.id),
        ev = evidenceFor(s, c.id),
        pm = poamsFor(s, c.id).filter((p) => p.status !== 'closed');
      line();
      line(`#### ${c.id} ${c.t}`);
      line();
      const meta = [`Status: ${a.status ? STATUS_LABEL[a.status] : 'Not assessed'}`];
      if (a.origin) meta.push(`Origin: ${a.origin}`);
      if (a.role) meta.push(`Responsible role: ${a.role}`);
      line(meta.join('. ') + '.');
      line();
      line('Control requirement:');
      line();
      line(statementText(c).split('\n').map((x) => '> ' + x).join('\n'));
      line();
      line('Implementation:');
      line();
      line(a.impl.trim() || '_Implementation statement needed._');
      if (ev.length) {
        line();
        line('Evidence:');
        line();
        ev.forEach((e) => line(`- ${e.id} ${e.title} (${e.fileName}, captured ${fmtDate(e.capturedAt)}, SHA-256 ${e.sha256})`));
      }
      if (pm.length) {
        line();
        line('Open POA&M items:');
        line();
        pm.forEach((p) => line(`- ${p.id} ${p.title} (${p.severity}, ${p.status.replace('-', ' ')}, due ${fmtDate(p.scheduledCompletion)})`));
      }
    }
  }
  line();
  return out.join('\n');
}

// ---------- SSP, OSCAL ----------
export function sspOscal(cat: Catalog, s: State): object {
  const sys = s.system,
    k = sysKey(s),
    lvl = `fips-199-${sys.baseline}`;
  const scope = inScope(cat, s);
  const roleTitles = new Map<string, string>();
  scope.forEach((c) => {
    const r = assessmentOf(s, c.id).role.trim();
    if (r) roleTitles.set(slug(r), r);
  });
  const parties: object[] = [],
    resp: object[] = [];
  const person = (role: string, name: string) => {
    if (!name.trim()) return;
    const u = uuidFor(k, 'party', role);
    parties.push({ uuid: u, type: 'person', name: name.trim() });
    resp.push({ 'role-id': role, 'party-uuids': [u] });
  };
  person('system-owner', sys.owner);
  person('information-system-security-officer', sys.isso);
  const thisSystem = uuidFor(k, 'component', 'this-system');
  const reqs = scope.map((c) => {
    const a = assessmentOf(s, c.id);
    const bc: Record<string, unknown> = {
      'component-uuid': thisSystem,
      uuid: uuidFor(k, 'by-component', c.id),
      description: a.impl.trim() || 'Implementation statement needed.',
    };
    if (a.status) bc['implementation-status'] = { state: OSCAL_STATE[a.status] };
    if (a.role.trim()) bc['responsible-roles'] = [{ 'role-id': slug(a.role) }];
    const ir: Record<string, unknown> = { uuid: uuidFor(k, 'req', c.id), 'control-id': c.o, 'by-components': [bc] };
    const props: object[] = [];
    if (a.origin) props.push({ name: 'control-origination', ns: NS, value: a.origin });
    const ev = evidenceFor(s, c.id);
    if (ev.length) ir.links = ev.map((e) => ({ href: `#${uuidFor(k, 'evidence', e.id)}`, rel: 'evidence', text: `${e.id} ${e.title}` }));
    if (props.length) ir.props = props;
    return ir;
  });
  const resources = s.evidence.map((e) => ({
    uuid: uuidFor(k, 'evidence', e.id),
    title: `${e.id} ${e.title}`,
    props: [{ name: 'type', value: 'evidence' }],
    rlinks: [{ href: e.fileName, 'media-type': e.mime || 'application/octet-stream', hashes: [{ algorithm: 'SHA-256', value: e.sha256 }] }],
    remarks: `Captured ${e.capturedAt}. Supports ${e.controlIds.join(', ')}.${e.notes ? ' ' + e.notes : ''}`,
  }));
  const ssp: Record<string, unknown> = {
    uuid: uuidFor(k, 'ssp'),
    metadata: {
      title: `${sys.name || 'Untitled system'} System Security Plan`,
      'last-modified': nowStamp(),
      version: 'draft',
      'oscal-version': OSCAL_VERSION,
      roles: [
        { id: 'system-owner', title: 'System Owner' },
        { id: 'information-system-security-officer', title: 'Information System Security Officer' },
        ...[...roleTitles].filter(([id]) => id !== 'system-owner' && id !== 'information-system-security-officer').map(([id, title]) => ({ id, title })),
      ],
      ...(parties.length ? { parties, 'responsible-parties': resp } : {}),
      remarks: `Generated by Preflight.${s.demo ? ' Sample data for a fictional system.' : ''}`,
    },
    'import-profile': { href: PROFILE(sys.baseline) },
    'system-characteristics': {
      'system-ids': [{ 'identifier-type': 'https://ietf.org/rfc/rfc4122', id: uuidFor(k, 'system-id') }],
      'system-name': sys.name || 'Untitled system',
      ...(sys.short ? { 'system-name-short': sys.short } : {}),
      description: sys.description || 'System description needed.',
      'security-sensitivity-level': lvl,
      'system-information': {
        'information-types': [
          {
            uuid: uuidFor(k, 'info-type'),
            title: 'System information',
            description: 'Information types to be categorized under NIST SP 800-60. Impact levels follow the selected baseline until then.',
            'confidentiality-impact': { base: lvl },
            'integrity-impact': { base: lvl },
            'availability-impact': { base: lvl },
          },
        ],
      },
      'security-impact-level': { 'security-objective-confidentiality': lvl, 'security-objective-integrity': lvl, 'security-objective-availability': lvl },
      status: { state: sys.status },
      'authorization-boundary': { description: sys.boundary || 'Authorization boundary description needed.' },
    },
    'system-implementation': {
      components: [{ uuid: thisSystem, type: 'this-system', title: sys.name || 'This system', description: sys.description || 'The system as a whole.', status: { state: 'operational' } }],
    },
    'control-implementation': {
      description: `Implementation of the NIST SP 800-53 Rev. 5 ${sys.baseline} baseline${sys.privacy ? ' and the privacy baseline' : ''}.`,
      'implemented-requirements': reqs,
    },
  };
  if (resources.length) ssp['back-matter'] = { resources };
  return { 'system-security-plan': ssp };
}

// ---------- POA&M, OSCAL ----------
export function poamOscal(s: State): object {
  const k = sysKey(s);
  const risks = s.poams.map((p) => {
    const rid = uuidFor(k, 'risk', p.id);
    const risk: Record<string, unknown> = {
      uuid: rid,
      title: p.title,
      description: p.description || p.title,
      statement: p.residualRisk.trim() || `Weakness against ${p.controlId}, ${p.severity} severity.`,
      props: [
        { name: 'severity', ns: NS, value: p.severity },
        { name: 'control-id', ns: NS, value: p.controlId },
      ],
      status: RISK_STATE[p.status],
    };
    if (p.scheduledCompletion) risk.deadline = p.scheduledCompletion + 'T23:59:59Z';
    if (p.milestones.length)
      risk.remediations = [
        {
          uuid: uuidFor(k, 'remediation', p.id),
          lifecycle: 'planned',
          title: `Remediation plan for ${p.id}`,
          description: p.description || p.title,
          tasks: p.milestones.map((m, i) => ({
            uuid: uuidFor(k, 'milestone', p.id, String(i)),
            type: 'milestone',
            title: m.text || `Milestone ${i + 1}`,
            ...(m.due ? { timing: { 'on-date': { date: m.due + 'T23:59:59Z' } } } : {}),
            props: [{ name: 'completed', ns: NS, value: m.done ? 'yes' : 'no' }],
          })),
        },
      ];
    return risk;
  });
  const items = s.poams.map((p) => ({
    uuid: uuidFor(k, 'poam-item', p.id),
    title: p.title,
    description: p.description || p.title,
    props: [
      { name: 'POAM-ID', ns: NS, value: p.id },
      { name: 'source', ns: NS, value: p.source },
      { name: 'point-of-contact', ns: NS, value: p.poc || 'unassigned' },
      { name: 'detected', ns: NS, value: p.created },
    ],
    'related-risks': [{ 'risk-uuid': uuidFor(k, 'risk', p.id) }],
    ...(p.residualRisk.trim() ? { remarks: `Residual risk: ${p.residualRisk.trim()}` } : {}),
  }));
  const poam: Record<string, unknown> = {
    uuid: uuidFor(k, 'poam'),
    metadata: {
      title: `${s.system.name || 'Untitled system'} Plan of Action and Milestones`,
      'last-modified': nowStamp(),
      version: 'draft',
      'oscal-version': OSCAL_VERSION,
      ...(s.demo ? { remarks: 'Sample data for a fictional system.' } : {}),
    },
    'system-id': { 'identifier-type': 'https://ietf.org/rfc/rfc4122', id: uuidFor(k, 'system-id') },
    'poam-items': items.length ? items : [{ uuid: uuidFor(k, 'poam-item', 'none'), title: 'No open items', description: 'No weaknesses recorded.' }],
  };
  if (risks.length) poam.risks = risks;
  return { 'plan-of-action-and-milestones': poam };
}

// ---------- POA&M, CSV ----------
const csvCell = (v: unknown) => {
  const t = String(v ?? '');
  return /[",\n]/.test(t) ? `"${t.replace(/"/g, '""')}"` : t;
};
export function poamCsv(s: State): string {
  const head = ['POA&M ID', 'Control', 'Weakness', 'Description', 'Severity', 'Status', 'Source', 'Point of contact', 'Detected', 'Scheduled completion', 'Milestones', 'Overdue', 'Residual risk', 'Completed'];
  const rows = s.poams.map((p: PoamItem) => [
    p.id, p.controlId, p.title, p.description, p.severity, p.status, p.source, p.poc, p.created, p.scheduledCompletion,
    p.milestones.map((m) => `${m.due} ${m.done ? '[done]' : '[open]'} ${m.text}`).join('; '),
    isOverdue(p) ? 'yes' : 'no', p.residualRisk, p.closedAt || '',
  ]);
  return [head, ...rows].map((r) => r.map(csvCell).join(',')).join('\r\n') + '\r\n';
}

// ---------- backup ----------
export const BACKUP_FORMAT = 'preflight-backup';

async function b64(b: Blob): Promise<string> {
  const u = new Uint8Array(await b.arrayBuffer());
  let s = '';
  for (let i = 0; i < u.length; i += 0x8000) s += String.fromCharCode(...u.subarray(i, i + 0x8000));
  return btoa(s);
}
export async function backupJson(s: State, files: Record<string, Blob>): Promise<string> {
  const f: Record<string, string> = {};
  for (const [id, b] of Object.entries(files)) if (s.evidence.some((e) => e.id === id)) f[id] = await b64(b);
  return JSON.stringify({ format: BACKUP_FORMAT, version: 1, exported: nowStamp(), state: s, files: f });
}

export interface Restored {
  state: State;
  files: Record<string, Blob>;
  mismatched: string[]; // evidence whose file no longer matches its recorded fingerprint
  missing: string[]; // evidence with no file in the backup
}
export async function readBackup(text: string): Promise<Restored> {
  let o: any;
  try {
    o = JSON.parse(text);
  } catch {
    throw new Error('This file is not JSON. Choose a backup exported from Preflight.');
  }
  if (!o || o.format !== BACKUP_FORMAT || !o.state || !o.state.system || !Array.isArray(o.state.evidence) || !Array.isArray(o.state.poams))
    throw new Error('This is not a Preflight backup. Choose a file exported with "Download backup".');
  if (o.version !== 1) throw new Error(`This backup is version ${o.version}; this copy of Preflight reads version 1.`);
  const st = o.state as State;
  if (!['low', 'moderate', 'high'].includes(st.system.baseline)) throw new Error('The backup has an unknown baseline.');
  st.a = st.a || {};
  st.seq = st.seq || { ev: st.evidence.length, poam: st.poams.length };
  const files: Record<string, Blob> = {},
    mismatched: string[] = [],
    missing: string[] = [];
  for (const e of st.evidence) {
    const data = o.files && o.files[e.id];
    if (!data) {
      missing.push(e.id);
      continue;
    }
    const bin = atob(data),
      u = new Uint8Array(bin.length);
    for (let i = 0; i < bin.length; i++) u[i] = bin.charCodeAt(i);
    const blob = new Blob([u], { type: e.mime || 'application/octet-stream' });
    if ((await sha256(u.buffer)) !== e.sha256) mismatched.push(e.id);
    files[e.id] = blob;
  }
  return { state: st, files, mismatched, missing };
}

export function fileStem(s: State): string {
  return (s.system.short || s.system.name || 'system').toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '') || 'system';
}
